# Brand names, protocol names, identifiers, ratios and SI/time units should
# remain unchanged in the Chinese catalogue.
KEEP = {
    "", "#", "#%1", "(", "1080p", "1440p", "16:9", "1:1", "2160p",
    "4:3", "720p", "9:16", "Flatpak", "GitHub", "ID", "ID:", "Id",
    "hypengw", "h", "m", "ms", "s", "v", "waywallen",
}


def main() -> None:
    tree = ET.parse(CATALOGUE)
    root = tree.getroot()
    missing: set[str] = set()
    for message in root.iter("message"):
        source = message.findtext("source") or ""
        value = ZH.get(source)
        if value is None:
            if source not in KEEP:
                missing.add(source)
            value = source
        translation = message.find("translation")
        if translation is None:
            translation = ET.SubElement(message, "translation")
        translation.attrib.pop("type", None)
        translation.text = value

    if missing:
        raise SystemExit("Missing translations:\n" + "\n".join(sorted(missing)))

    ET.indent(tree, space="    ")
    tree.write(CATALOGUE, encoding="utf-8", xml_declaration=True)


if __name__ == "__main__":
    main()
